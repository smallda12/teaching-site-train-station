/* ---------- 資源路徑輔助（app.js 直接呼叫這幾個全域函式） ----------
   圖片檔名固定（p01.webp…），改版後重新輸出還是同一個檔名，
   所以要帶 資源版本 參數，否則瀏覽器會繼續顯示快取裡的舊頁面。
   🛑 這一段少寫的話，app.js 第一次呼叫 資源v() 就 ReferenceError，
      **整個初始化會靜靜中止**：畫面看起來正常（靜態 HTML 還在），
      但重點卡、圖卡牆、影片清單全都是空的，主控台也不一定看得到錯誤。 */
const 資源v = () => `?v=${(window.CONFIG && CONFIG.資源版本) || 1}`;
